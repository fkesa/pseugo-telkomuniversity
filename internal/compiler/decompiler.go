package compiler

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"strconv"
	"strings"
)

// DecompileGo converts Go source code into pseudocode source code.
func DecompileGo(goSource string) (string, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "", goSource, parser.ParseComments)
	if err != nil {
		return "", fmt.Errorf("failed to parse Go source: %w", err)
	}

	d := newDecompiler()
	return d.decompileFile(file)
}

type decompiler struct {
	globalTypes     []*ast.TypeSpec
	globalVars      []*ast.ValueSpec
	globalConstants []*ast.ValueSpec
	varTypes        map[string]string
	targetRealHint  bool
}

func newDecompiler() *decompiler {
	return &decompiler{
		varTypes: make(map[string]string),
	}
}

func (d *decompiler) decompileFile(file *ast.File) (string, error) {
	// First pass: collect package-level declarations and functions
	var funcs []*ast.FuncDecl
	funcNames := make(map[string]bool)

	for _, decl := range file.Decls {
		switch v := decl.(type) {
		case *ast.GenDecl:
			switch v.Tok {
			case token.TYPE:
				for _, spec := range v.Specs {
					if ts, ok := spec.(*ast.TypeSpec); ok {
						d.globalTypes = append(d.globalTypes, ts)
					}
				}
			case token.CONST:
				for _, spec := range v.Specs {
					if vs, ok := spec.(*ast.ValueSpec); ok {
						d.globalConstants = append(d.globalConstants, vs)
					}
				}
			case token.VAR:
				for _, spec := range v.Specs {
					if vs, ok := spec.(*ast.ValueSpec); ok {
						d.globalVars = append(d.globalVars, vs)
					}
				}
			}
		case *ast.FuncDecl:
			funcs = append(funcs, v)
			funcNames[v.Name.Name] = true
		}
	}

	// Determine which functions represent programs.
	// If generated by pseudocode-compiler, there are subprogram functions and a "main" function
	// that only calls them in sequence.
	var programFuncs []*ast.FuncDecl
	mainIsRunner := false

	var mainFunc *ast.FuncDecl
	for _, fn := range funcs {
		if fn.Name.Name == "main" {
			mainFunc = fn
			break
		}
	}

	if mainFunc != nil && len(funcs) > 1 {
		mainIsRunner = d.isRunnerFunction(mainFunc, funcNames)
	}

	for _, fn := range funcs {
		if fn.Name.Name == "main" && mainIsRunner {
			continue // skip runner main
		}
		programFuncs = append(programFuncs, fn)
	}

	if len(programFuncs) == 0 && mainFunc != nil {
		programFuncs = append(programFuncs, mainFunc)
	}

	if len(programFuncs) == 0 {
		return "", fmt.Errorf("no functions found to decompile")
	}

	var sb strings.Builder
	for i, fn := range programFuncs {
		if i > 0 {
			sb.WriteString("\n\n")
		}
		progStr, err := d.decompileProgram(fn)
		if err != nil {
			return "", err
		}
		sb.WriteString(progStr)
	}

	result := sb.String()
	// Run pseudocode typechecker before returning converted pseudocode
	if _, err := CheckSource(result); err != nil {
		return result, fmt.Errorf("decompiled pseudocode failed typecheck: %w", err)
	}
	return result, nil
}

func (d *decompiler) isRunnerFunction(fn *ast.FuncDecl, knownFuncs map[string]bool) bool {
	if fn.Body == nil || len(fn.Body.List) == 0 {
		return false
	}
	for _, stmt := range fn.Body.List {
		exprStmt, ok := stmt.(*ast.ExprStmt)
		if !ok {
			return false
		}
		call, ok := exprStmt.X.(*ast.CallExpr)
		if !ok {
			return false
		}
		ident, ok := call.Fun.(*ast.Ident)
		if !ok || !knownFuncs[ident.Name] || ident.Name == "main" {
			return false
		}
	}
	return true
}

func (d *decompiler) decompileProgram(fn *ast.FuncDecl) (string, error) {
	progName := cleanIdent(fn.Name.Name)

	pCtx := &programContext{
		parent:   d,
		varTypes: make(map[string]string),
	}

	// Register global types
	for _, ts := range d.globalTypes {
		pCtx.types = append(pCtx.types, ts)
	}

	// Register global constants
	for _, cs := range d.globalConstants {
		pCtx.constants = append(pCtx.constants, cs)
		for _, name := range cs.Names {
			t := d.inferTypeFromExpr(cs.Values[0], pCtx.varTypes)
			if cs.Type != nil {
				t = d.goTypeToPseudo(cs.Type)
			}
			pCtx.varTypes[cleanIdent(name.Name)] = t
		}
	}

	// Register global vars
	for _, vs := range d.globalVars {
		pCtx.vars = append(pCtx.vars, vs)
		t := "integer"
		if vs.Type != nil {
			t = d.goTypeToPseudo(vs.Type)
		}
		for _, name := range vs.Names {
			pCtx.varTypes[cleanIdent(name.Name)] = t
		}
	}

	// Scan function body for local declarations and variables
	if fn.Body != nil {
		pCtx.collectLocalDecls(fn.Body.List)
	}

	var sb strings.Builder
	sb.WriteString("program ")
	sb.WriteString(progName)
	sb.WriteString("\n")
	sb.WriteString("kamus\n")

	// Emit types
	for _, ts := range pCtx.types {
		st, ok := ts.Type.(*ast.StructType)
		if !ok {
			continue
		}
		typeName := cleanIdent(ts.Name.Name)
		sb.WriteString("    type ")
		sb.WriteString(typeName)
		sb.WriteString(" <\n")
		for _, field := range st.Fields.List {
			fType := d.goTypeToPseudo(field.Type)
			for _, fName := range field.Names {
				sb.WriteString("        ")
				sb.WriteString(cleanIdent(fName.Name))
				sb.WriteString(" : ")
				sb.WriteString(fType)
				sb.WriteString("\n")
				pCtx.recordFields[typeName+"."+cleanIdent(fName.Name)] = fType
			}
		}
		sb.WriteString("    >\n")
	}

	// Emit constants
	for _, cs := range pCtx.constants {
		for i, name := range cs.Names {
			cName := cleanIdent(name.Name)
			var cVal ast.Expr
			if i < len(cs.Values) {
				cVal = cs.Values[i]
			}
			cType := pCtx.varTypes[cName]
			if cType == "" {
				cType = TypeInteger
			}
			valStr := pCtx.exprToPseudo(cVal)
			sb.WriteString("    constant ")
			sb.WriteString(cName)
			sb.WriteString(" : ")
			sb.WriteString(cType)
			sb.WriteString(" <- ")
			sb.WriteString(valStr)
			sb.WriteString("\n")
		}
	}

	// Emit variables grouped by type in order of discovery
	for _, typ := range pCtx.typeOrder {
		names := pCtx.groupedVars[typ]
		if len(names) > 0 {
			sb.WriteString("    ")
			sb.WriteString(strings.Join(names, ", "))
			sb.WriteString(" : ")
			sb.WriteString(typ)
			sb.WriteString("\n")
		}
	}

	sb.WriteString("algoritma\n")

	if fn.Body != nil {
		for _, stmt := range fn.Body.List {
			lines := pCtx.decompileStmt(stmt, 1)
			for _, line := range lines {
				sb.WriteString(line)
				sb.WriteString("\n")
			}
		}
	}

	sb.WriteString("endprogram")
	return sb.String(), nil
}

type programContext struct {
	parent       *decompiler
	types        []*ast.TypeSpec
	constants    []*ast.ValueSpec
	vars         []*ast.ValueSpec
	varTypes     map[string]string
	recordFields map[string]string
	typeOrder    []string
	groupedVars  map[string][]string
	seenVars     map[string]bool
}

func (p *programContext) addVar(name, typ string) {
	name = cleanIdent(name)
	if p.seenVars[name] {
		return
	}
	p.seenVars[name] = true
	p.varTypes[name] = typ
	if p.groupedVars == nil {
		p.groupedVars = make(map[string][]string)
	}
	if len(p.groupedVars[typ]) == 0 {
		p.typeOrder = append(p.typeOrder, typ)
	}
	p.groupedVars[typ] = append(p.groupedVars[typ], name)
}

func (p *programContext) collectLocalDecls(stmts []ast.Stmt) {
	if p.seenVars == nil {
		p.seenVars = make(map[string]bool)
	}
	if p.recordFields == nil {
		p.recordFields = make(map[string]string)
	}

	for _, stmt := range stmts {
		switch s := stmt.(type) {
		case *ast.DeclStmt:
			gd, ok := s.Decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			switch gd.Tok {
			case token.TYPE:
				for _, spec := range gd.Specs {
					if ts, ok := spec.(*ast.TypeSpec); ok {
						p.types = append(p.types, ts)
					}
				}
			case token.CONST:
				for _, spec := range gd.Specs {
					if vs, ok := spec.(*ast.ValueSpec); ok {
						p.constants = append(p.constants, vs)
						for i, name := range vs.Names {
							cName := cleanIdent(name.Name)
							var t string
							if vs.Type != nil {
								t = p.parent.goTypeToPseudo(vs.Type)
							} else if i < len(vs.Values) {
								t = p.inferType(vs.Values[i])
							}
							p.varTypes[cName] = t
							p.seenVars[cName] = true
						}
					}
				}
			case token.VAR:
				for _, spec := range gd.Specs {
					if vs, ok := spec.(*ast.ValueSpec); ok {
						t := "integer"
						if vs.Type != nil {
							t = p.parent.goTypeToPseudo(vs.Type)
						}
						for _, name := range vs.Names {
							p.addVar(name.Name, t)
						}
					}
				}
			}
		case *ast.AssignStmt:
			if s.Tok == token.DEFINE { // := short var declaration
				for i, lhs := range s.Lhs {
					if id, ok := lhs.(*ast.Ident); ok {
						name := cleanIdent(id.Name)
						var t string
						if i < len(s.Rhs) {
							t = p.inferType(s.Rhs[i])
						}
						if t == "" {
							t = TypeInteger
						}
						p.addVar(name, t)
					}
				}
			}
		case *ast.ForStmt:
			// Check counter variable in loop init
			if s.Init != nil {
				if assign, ok := s.Init.(*ast.AssignStmt); ok {
					for _, lhs := range assign.Lhs {
						if id, ok := lhs.(*ast.Ident); ok {
							p.addVar(id.Name, TypeInteger)
						}
					}
				}
			}
			p.collectLocalDecls(s.Body.List)
		case *ast.IfStmt:
			if s.Init != nil {
				if assign, ok := s.Init.(*ast.AssignStmt); ok && assign.Tok == token.DEFINE {
					for _, lhs := range assign.Lhs {
						if id, ok := lhs.(*ast.Ident); ok {
							p.addVar(id.Name, p.inferType(assign.Rhs[0]))
						}
					}
				}
			}
			p.collectLocalDecls(s.Body.List)
			if s.Else != nil {
				if block, ok := s.Else.(*ast.BlockStmt); ok {
					p.collectLocalDecls(block.List)
				} else if ifElse, ok := s.Else.(*ast.IfStmt); ok {
					p.collectLocalDecls([]ast.Stmt{ifElse})
				}
			}
		case *ast.SwitchStmt:
			if s.Body != nil {
				for _, stmt := range s.Body.List {
					if cc, ok := stmt.(*ast.CaseClause); ok {
						p.collectLocalDecls(cc.Body)
					}
				}
			}
		case *ast.BlockStmt:
			p.collectLocalDecls(s.List)
		}
	}
}

func (p *programContext) inferType(expr ast.Expr) string {
	return p.parent.inferTypeFromExpr(expr, p.varTypes)
}

func (d *decompiler) inferTypeFromExpr(expr ast.Expr, env map[string]string) string {
	if expr == nil {
		return TypeInteger
	}
	switch e := expr.(type) {
	case *ast.BasicLit:
		switch e.Kind {
		case token.INT:
			return TypeInteger
		case token.FLOAT:
			return TypeReal
		case token.STRING:
			return TypeString
		case token.CHAR:
			return TypeChar
		}
	case *ast.Ident:
		clean := cleanIdent(e.Name)
		if clean == "true" || clean == "false" || clean == "benar" || clean == "salah" {
			return TypeBoolean
		}
		if t, ok := env[clean]; ok {
			return t
		}
	case *ast.ParenExpr:
		return d.inferTypeFromExpr(e.X, env)
	case *ast.UnaryExpr:
		if e.Op == token.NOT {
			return TypeBoolean
		}
		return d.inferTypeFromExpr(e.X, env)
	case *ast.BinaryExpr:
		switch e.Op {
		case token.LAND, token.LOR, token.EQL, token.NEQ, token.LSS, token.LEQ, token.GTR, token.GEQ:
			return TypeBoolean
		case token.QUO:
			// Division in Go: check if float64 cast was used, or if either operand is real
			leftType := d.inferTypeFromExpr(e.X, env)
			rightType := d.inferTypeFromExpr(e.Y, env)
			if leftType == TypeReal || rightType == TypeReal {
				return TypeReal
			}
			// In Go, int / int is integer division DIV
			return TypeInteger
		case token.REM:
			return TypeInteger
		default:
			leftType := d.inferTypeFromExpr(e.X, env)
			rightType := d.inferTypeFromExpr(e.Y, env)
			if leftType == TypeReal || rightType == TypeReal {
				return TypeReal
			}
			return TypeInteger
		}
	case *ast.CallExpr:
		if funIdent, ok := e.Fun.(*ast.Ident); ok {
			switch funIdent.Name {
			case "float64", "float32":
				return TypeReal
			case "int", "int32", "int64":
				return TypeInteger
			case "string":
				return TypeString
			case "rune", "byte":
				return TypeChar
			case "bool":
				return TypeBoolean
			}
		}
	case *ast.SelectorExpr:
		baseId, ok := e.X.(*ast.Ident)
		if ok {
			baseName := cleanIdent(baseId.Name)
			recType := env[baseName]
			fieldName := cleanIdent(e.Sel.Name)
			for _, ts := range d.globalTypes {
				if cleanIdent(ts.Name.Name) == recType || cleanIdent(ts.Name.Name) == baseName {
					if st, ok := ts.Type.(*ast.StructType); ok {
						for _, f := range st.Fields.List {
							for _, fn := range f.Names {
								if cleanIdent(fn.Name) == fieldName {
									return d.goTypeToPseudo(f.Type)
								}
							}
						}
					}
				}
			}
		}
	}
	return TypeInteger
}

func (d *decompiler) goTypeToPseudo(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		switch strings.ToLower(t.Name) {
		case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64":
			return TypeInteger
		case "float32", "float64":
			return TypeReal
		case "bool":
			return TypeBoolean
		case "string":
			return TypeString
		case "byte", "rune", "char":
			return TypeChar
		default:
			return cleanIdent(t.Name)
		}
	default:
		return TypeInteger
	}
}

func (p *programContext) indent(level int) string {
	return strings.Repeat("    ", level)
}

func (p *programContext) decompileStmt(stmt ast.Stmt, level int) []string {
	ind := p.indent(level)
	switch s := stmt.(type) {
	case *ast.DeclStmt:
		// Check if var declaration with initial values
		gd, ok := s.Decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.VAR {
			return nil
		}
		var lines []string
		for _, spec := range gd.Specs {
			if vs, ok := spec.(*ast.ValueSpec); ok {
				for i, name := range vs.Names {
					if i < len(vs.Values) && vs.Values[i] != nil {
						target := cleanIdent(name.Name)
						valStr := p.exprToPseudo(vs.Values[i])
						lines = append(lines, ind+target+" <- "+valStr)
					}
				}
			}
		}
		return lines

	case *ast.AssignStmt:
		var lines []string
		for i, lhs := range s.Lhs {
			target := p.exprToPseudo(lhs)
			var rhs ast.Expr
			if i < len(s.Rhs) {
				rhs = s.Rhs[i]
			}
			targetType := p.getExprType(lhs)

			switch s.Tok {
			case token.ASSIGN, token.DEFINE:
				// If target is real and rhs is a division between ints, e.g. rata_rata <- jumlah / n
				valStr := p.exprToPseudoWithTarget(rhs, targetType)
				lines = append(lines, ind+target+" <- "+valStr)
			case token.ADD_ASSIGN:
				lines = append(lines, ind+target+" <- "+target+" + "+p.exprToPseudo(rhs))
			case token.SUB_ASSIGN:
				lines = append(lines, ind+target+" <- "+target+" - "+p.exprToPseudo(rhs))
			case token.MUL_ASSIGN:
				lines = append(lines, ind+target+" <- "+target+" * "+p.exprToPseudo(rhs))
			case token.QUO_ASSIGN:
				op := "/"
				if targetType == TypeInteger {
					op = "DIV"
				}
				lines = append(lines, ind+target+" <- "+target+" "+op+" "+p.exprToPseudo(rhs))
			case token.REM_ASSIGN:
				lines = append(lines, ind+target+" <- "+target+" MOD "+p.exprToPseudo(rhs))
			}
		}
		return lines

	case *ast.IncDecStmt:
		target := p.exprToPseudo(s.X)
		if s.Tok == token.INC {
			return []string{ind + target + " <- " + target + " + 1"}
		}
		return []string{ind + target + " <- " + target + " - 1"}

	case *ast.ExprStmt:
		call, ok := s.X.(*ast.CallExpr)
		if !ok {
			return nil
		}
		return p.decompileCall(call, ind)

	case *ast.IfStmt:
		return p.decompileIf(s, level)

	case *ast.ForStmt:
		return p.decompileFor(s, level)

	case *ast.SwitchStmt:
		return p.decompileSwitch(s, level)

	case *ast.BlockStmt:
		var lines []string
		for _, child := range s.List {
			lines = append(lines, p.decompileStmt(child, level)...)
		}
		return lines
	}
	return nil
}

func (p *programContext) getExprType(e ast.Expr) string {
	switch v := e.(type) {
	case *ast.Ident:
		return p.varTypes[cleanIdent(v.Name)]
	case *ast.SelectorExpr:
		base := p.exprToPseudo(v.X)
		field := cleanIdent(v.Sel.Name)
		if t, ok := p.recordFields[base+"."+field]; ok {
			return t
		}
		recType := p.varTypes[base]
		if t, ok := p.recordFields[recType+"."+field]; ok {
			return t
		}
	}
	return ""
}

func (p *programContext) decompileCall(call *ast.CallExpr, ind string) []string {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return nil
	}
	pkgIdent, ok := sel.X.(*ast.Ident)
	if !ok || pkgIdent.Name != "fmt" {
		return nil
	}

	fnName := sel.Sel.Name
	switch fnName {
	case "Scan", "Scanln":
		var targets []string
		for _, arg := range call.Args {
			targets = append(targets, p.exprToPseudo(arg))
		}
		if len(targets) > 0 {
			return []string{ind + "input(" + strings.Join(targets, ", ") + ")"}
		}
	case "Scanf":
		var targets []string
		// First arg is format string
		args := call.Args
		if len(args) > 1 {
			args = args[1:]
		}
		for _, arg := range args {
			targets = append(targets, p.exprToPseudo(arg))
		}
		if len(targets) > 0 {
			return []string{ind + "input(" + strings.Join(targets, ", ") + ")"}
		}
	case "Println", "Print":
		var values []string
		for _, arg := range call.Args {
			values = append(values, p.exprToPseudo(arg))
		}
		return []string{ind + "output(" + strings.Join(values, ", ") + ")"}
	case "Printf":
		var values []string
		args := call.Args
		if len(args) > 1 {
			for _, arg := range args[1:] {
				values = append(values, p.exprToPseudo(arg))
			}
		} else if len(args) == 1 {
			values = append(values, p.exprToPseudo(args[0]))
		}
		return []string{ind + "output(" + strings.Join(values, ", ") + ")"}
	}
	return nil
}

func (p *programContext) decompileIf(s *ast.IfStmt, level int) []string {
	ind := p.indent(level)
	var lines []string

	condStr := p.exprToPseudo(s.Cond)
	lines = append(lines, ind+"if "+condStr+" then")

	for _, stmt := range s.Body.List {
		lines = append(lines, p.decompileStmt(stmt, level+1)...)
	}

	currElse := s.Else
	for currElse != nil {
		if ifElse, ok := currElse.(*ast.IfStmt); ok {
			elseCond := p.exprToPseudo(ifElse.Cond)
			lines = append(lines, ind+"elseif "+elseCond+" then")
			for _, stmt := range ifElse.Body.List {
				lines = append(lines, p.decompileStmt(stmt, level+1)...)
			}
			currElse = ifElse.Else
		} else if block, ok := currElse.(*ast.BlockStmt); ok {
			lines = append(lines, ind+"else")
			for _, stmt := range block.List {
				lines = append(lines, p.decompileStmt(stmt, level+1)...)
			}
			break
		} else {
			break
		}
	}

	lines = append(lines, ind+"endif")
	return lines
}

func (p *programContext) decompileSwitch(s *ast.SwitchStmt, level int) []string {
	ind := p.indent(level)
	var lines []string

	// Tagless switch: switch { case cond1: ... default: ... }
	if s.Tag == nil {
		if s.Body == nil || len(s.Body.List) == 0 {
			return nil
		}
		first := true
		for _, stmt := range s.Body.List {
			cc, ok := stmt.(*ast.CaseClause)
			if !ok {
				continue
			}
			if len(cc.List) > 0 {
				var conds []string
				for _, c := range cc.List {
					conds = append(conds, p.exprToPseudo(c))
				}
				condStr := strings.Join(conds, " OR ")
				if first {
					lines = append(lines, ind+"if "+condStr+" then")
					first = false
				} else {
					lines = append(lines, ind+"elseif "+condStr+" then")
				}
				for _, b := range cc.Body {
					lines = append(lines, p.decompileStmt(b, level+1)...)
				}
			} else {
				// default
				lines = append(lines, ind+"else")
				for _, b := range cc.Body {
					lines = append(lines, p.decompileStmt(b, level+1)...)
				}
			}
		}
		if !first {
			lines = append(lines, ind+"endif")
		}
		return lines
	}

	// Tagged switch: depend on expr
	exprStr := p.exprToPseudo(s.Tag)
	lines = append(lines, ind+"depend on "+exprStr)

	if s.Body != nil {
		for _, stmt := range s.Body.List {
			cc, ok := stmt.(*ast.CaseClause)
			if !ok {
				continue
			}
			if len(cc.List) > 0 {
				var vals []string
				for _, v := range cc.List {
					vals = append(vals, p.exprToPseudo(v))
				}
				lines = append(lines, p.indent(level+1)+strings.Join(vals, ", ")+":")
				for _, b := range cc.Body {
					lines = append(lines, p.decompileStmt(b, level+2)...)
				}
			} else {
				lines = append(lines, p.indent(level+1)+"default:")
				for _, b := range cc.Body {
					lines = append(lines, p.decompileStmt(b, level+2)...)
				}
			}
		}
	}

	lines = append(lines, ind+"enddepend")
	return lines
}

func (p *programContext) decompileFor(s *ast.ForStmt, level int) []string {
	ind := p.indent(level)

	// Case 1: Repeat-Until loop
	// for { ... if cond { break } }
	if s.Init == nil && s.Cond == nil && s.Post == nil {
		if len(s.Body.List) > 0 {
			lastStmt := s.Body.List[len(s.Body.List)-1]
			if ifStmt, ok := lastStmt.(*ast.IfStmt); ok {
				if len(ifStmt.Body.List) == 1 {
					if _, ok := ifStmt.Body.List[0].(*ast.BranchStmt); ok {
						condStr := p.exprToPseudo(ifStmt.Cond)
						var lines []string
						lines = append(lines, ind+"repeat")
						for _, stmt := range s.Body.List[:len(s.Body.List)-1] {
							lines = append(lines, p.decompileStmt(stmt, level+1)...)
						}
						lines = append(lines, ind+"until "+condStr)
						return lines
					}
				}
			}
		}
		// Generic infinite loop: while true do
		var lines []string
		lines = append(lines, ind+"while true do")
		for _, stmt := range s.Body.List {
			lines = append(lines, p.decompileStmt(stmt, level+1)...)
		}
		lines = append(lines, ind+"endwhile")
		return lines
	}

	// Case 2: While loop
	// for cond { ... }
	if s.Init == nil && s.Post == nil && s.Cond != nil {
		var lines []string
		condStr := p.exprToPseudo(s.Cond)
		lines = append(lines, ind+"while "+condStr+" do")
		for _, stmt := range s.Body.List {
			lines = append(lines, p.decompileStmt(stmt, level+1)...)
		}
		lines = append(lines, ind+"endwhile")
		return lines
	}

	// Case 3: Counted For Loop
	// for counter = start; counter <= end; counter++
	if s.Init != nil && s.Cond != nil && s.Post != nil {
		counter, start, isCountedInit := p.parseForInit(s.Init)
		end, down, isCountedCond := p.parseForCond(counter, s.Cond)
		isCountedPost := p.parseForPost(counter, s.Post, down)

		if isCountedInit && isCountedCond && isCountedPost {
			var lines []string
			dir := "to"
			if down {
				dir = "downto"
			}
			lines = append(lines, ind+"for "+counter+" <- "+start+" "+dir+" "+end+" do")
			for _, stmt := range s.Body.List {
				lines = append(lines, p.decompileStmt(stmt, level+1)...)
			}
			lines = append(lines, ind+"endfor")
			return lines
		}
	}

	// Fallback: init followed by while
	var lines []string
	if s.Init != nil {
		lines = append(lines, p.decompileStmt(s.Init, level)...)
	}
	condStr := "true"
	if s.Cond != nil {
		condStr = p.exprToPseudo(s.Cond)
	}
	lines = append(lines, ind+"while "+condStr+" do")
	for _, stmt := range s.Body.List {
		lines = append(lines, p.decompileStmt(stmt, level+1)...)
	}
	if s.Post != nil {
		lines = append(lines, p.decompileStmt(s.Post, level+1)...)
	}
	lines = append(lines, ind+"endwhile")
	return lines
}

func (p *programContext) parseForInit(stmt ast.Stmt) (counter, start string, ok bool) {
	assign, okAssign := stmt.(*ast.AssignStmt)
	if !okAssign || len(assign.Lhs) != 1 || len(assign.Rhs) != 1 {
		return "", "", false
	}
	id, okId := assign.Lhs[0].(*ast.Ident)
	if !okId {
		return "", "", false
	}
	return cleanIdent(id.Name), p.exprToPseudo(assign.Rhs[0]), true
}

func (p *programContext) parseForCond(counter string, cond ast.Expr) (end string, down, ok bool) {
	bin, okBin := cond.(*ast.BinaryExpr)
	if !okBin {
		return "", false, false
	}
	leftId, okLeft := bin.X.(*ast.Ident)
	if !okLeft || cleanIdent(leftId.Name) != counter {
		return "", false, false
	}

	switch bin.Op {
	case token.LEQ: // counter <= end
		return p.exprToPseudo(bin.Y), false, true
	case token.LSS: // counter < end => end - 1
		yStr := p.exprToPseudo(bin.Y)
		if n, err := strconv.ParseInt(yStr, 10, 64); err == nil {
			return strconv.FormatInt(n-1, 10), false, true
		}
		return "(" + yStr + " - 1)", false, true
	case token.GEQ: // counter >= end (downto)
		return p.exprToPseudo(bin.Y), true, true
	case token.GTR: // counter > end => end + 1
		yStr := p.exprToPseudo(bin.Y)
		if n, err := strconv.ParseInt(yStr, 10, 64); err == nil {
			return strconv.FormatInt(n+1, 10), true, true
		}
		return "(" + yStr + " + 1)", true, true
	}
	return "", false, false
}

func (p *programContext) parseForPost(counter string, post ast.Stmt, down bool) bool {
	switch s := post.(type) {
	case *ast.IncDecStmt:
		id, ok := s.X.(*ast.Ident)
		if !ok || cleanIdent(id.Name) != counter {
			return false
		}
		if down && s.Tok == token.DEC {
			return true
		}
		if !down && s.Tok == token.INC {
			return true
		}
	case *ast.AssignStmt:
		if len(s.Lhs) != 1 || len(s.Rhs) != 1 {
			return false
		}
		id, ok := s.Lhs[0].(*ast.Ident)
		if !ok || cleanIdent(id.Name) != counter {
			return false
		}
		if down && s.Tok == token.SUB_ASSIGN && p.exprToPseudo(s.Rhs[0]) == "1" {
			return true
		}
		if !down && s.Tok == token.ADD_ASSIGN && p.exprToPseudo(s.Rhs[0]) == "1" {
			return true
		}
	}
	return false
}

func (p *programContext) exprToPseudo(expr ast.Expr) string {
	return p.exprToPseudoWithTarget(expr, "")
}

func (p *programContext) exprToPseudoWithTarget(expr ast.Expr, targetType string) string {
	if expr == nil {
		return ""
	}
	switch e := expr.(type) {
	case *ast.Ident:
		clean := cleanIdent(e.Name)
		return clean
	case *ast.BasicLit:
		return e.Value
	case *ast.ParenExpr:
		return "(" + p.exprToPseudoWithTarget(e.X, targetType) + ")"
	case *ast.SelectorExpr:
		return p.exprToPseudo(e.X) + "." + cleanIdent(e.Sel.Name)
	case *ast.UnaryExpr:
		switch e.Op {
		case token.AND: // address-of in scan
			return p.exprToPseudo(e.X)
		case token.NOT:
			return "(NOT " + p.exprToPseudo(e.X) + ")"
		case token.SUB:
			return "-" + p.exprToPseudo(e.X)
		case token.ADD:
			return "+" + p.exprToPseudo(e.X)
		}
	case *ast.CallExpr:
		// Check for type conversions like float64(x), int(x), etc.
		if len(e.Args) == 1 {
			if id, ok := e.Fun.(*ast.Ident); ok {
				switch id.Name {
				case "float64", "float32", "int", "int32", "int64", "rune", "byte":
					return p.exprToPseudoWithTarget(e.Args[0], targetType)
				}
			}
		}
	case *ast.BinaryExpr:
		leftType := p.inferType(e.X)
		rightType := p.inferType(e.Y)

		op := ""
		switch e.Op {
		case token.LAND:
			op = "AND"
		case token.LOR:
			op = "OR"
		case token.EQL:
			op = "="
		case token.NEQ:
			op = "!="
		case token.LSS:
			op = "<"
		case token.LEQ:
			op = "<="
		case token.GTR:
			op = ">"
		case token.GEQ:
			op = ">="
		case token.ADD:
			op = "+"
		case token.SUB:
			op = "-"
		case token.MUL:
			op = "*"
		case token.REM:
			op = "MOD"
		case token.QUO:
			// Determine if division should be DIV or /
			hasFloatCast := isFloatCast(e.X) || isFloatCast(e.Y)
			if hasFloatCast || targetType == TypeReal || leftType == TypeReal || rightType == TypeReal {
				op = "/"
			} else {
				op = "DIV"
			}
		}

		leftStr := p.exprToPseudo(e.X)
		rightStr := p.exprToPseudo(e.Y)
		return leftStr + " " + op + " " + rightStr
	}
	return ""
}

func isFloatCast(e ast.Expr) bool {
	if call, ok := e.(*ast.CallExpr); ok {
		if id, ok := call.Fun.(*ast.Ident); ok {
			return id.Name == "float64" || id.Name == "float32"
		}
	}
	return false
}

func cleanIdent(name string) string {
	name = strings.TrimPrefix(name, "__pseudo_user_")
	return name
}
