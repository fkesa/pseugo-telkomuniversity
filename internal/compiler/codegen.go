package compiler

import (
	"fmt"
	"go/format"
	gotoken "go/token"
	"strconv"
	"strings"
)

type CodeGenerator struct {
	b            strings.Builder
	indent       int
	needsFmt     bool
	aliases      map[string]string
	varTypes     map[string]string
	recordFields map[string]map[string]string
}

func (g *CodeGenerator) line(s string) {
	g.b.WriteString(strings.Repeat("\t", g.indent))
	g.b.WriteString(s)
	g.b.WriteByte('\n')
}

func goIdent(name string) string {
	if gotoken.IsKeyword(name) || name == "main" || name == "pseudofmt" || name == "__pseudoInput" || name == "__pseudoOutput" {
		return "__pseudo_user_" + name
	}
	return name
}

func (g *CodeGenerator) resolveAlias(name string) string {
	seen := map[string]bool{}
	for g.aliases[name] != "" && !seen[name] {
		seen[name] = true
		name = g.aliases[name]
	}
	return name
}

func (g *CodeGenerator) identifier(name string) string { return goIdent(g.resolveAlias(name)) }

func (g *CodeGenerator) inputType(name string) string {
	parts := strings.Split(name, ".")

	// Input ke field record, misalnya pr.panjang.
	if len(parts) > 1 {
		recordType := g.varTypes[g.resolveAlias(parts[0])]
		fields := g.recordFields[recordType]
		if fields != nil {
			return fields[parts[len(parts)-1]]
		}
		return ""
	}

	return g.varTypes[g.resolveAlias(name)]
}

func (g *CodeGenerator) inputTarget(name string) string {
	parts := strings.Split(name, ".")

	target := g.identifier(parts[0])
	for _, field := range parts[1:] {
		target += "." + goIdent(field)
	}

	return target
}

func (g *CodeGenerator) exprToRawName(e Expr) string {
	switch v := e.(type) {
	case IdentExpr:
		return v.Name
	case FieldExpr:
		return g.exprToRawName(v.Base) + "." + v.Field
	default:
		return ""
	}
}

func GenerateGo(prog *Program) (string, error) {
	g := &CodeGenerator{
		aliases:      map[string]string{},
		varTypes:     map[string]string{},
		recordFields: map[string]map[string]string{},
	}
	typeNames := map[string]bool{}

	// Catat tipe setiap field record.
	for _, d := range prog.Decls {
		if td, ok := d.(TypeDecl); ok {
			typeNames[td.Name] = true
			fields := map[string]string{}

			for _, f := range td.Fields {
				for _, name := range f.Names {
					fields[name] = f.TypeName
				}
			}

			g.recordFields[td.Name] = fields
		}
	}

	declared := map[string]bool{}

	for _, d := range prog.Decls {
		vd, ok := d.(VarDecl)
		if !ok {
			continue
		}

		if len(vd.Names) == 1 &&
			!vd.Constant &&
			!isPrimitiveType(vd.TypeName) &&
			!typeNames[vd.TypeName] &&
			declared[vd.TypeName] {

			name := vd.Names[0]
			g.aliases[name] = g.resolveAlias(vd.TypeName)
			g.varTypes[name] = g.varTypes[g.resolveAlias(vd.TypeName)]
			declared[name] = true

		} else {
			for _, name := range vd.Names {
				declared[name] = true
				g.varTypes[name] = vd.TypeName
			}
		}
	}

	for _, s := range prog.Body {
		g.scanRuntimeNeeds(s)
	}

	g.line("// Code generated by pseudocode-compiler. DO NOT EDIT.")
	g.line("package main")
	g.line("")
	if g.needsFmt {
		g.line("import \"fmt\"")
		g.line("")
	}

	for _, d := range prog.Decls {
		switch v := d.(type) {
		case TypeDecl:
			g.line("type " + goIdent(v.Name) + " struct {")
			g.indent++
			for _, f := range v.Fields {
				for _, name := range f.Names {
					g.line(goIdent(name) + " " + goType(f.TypeName))
				}
			}
			g.indent--
			g.line("}")
		case VarDecl:
			if len(v.Names) == 1 && g.aliases[v.Names[0]] != "" {
				continue
			}
			typ := goType(v.TypeName)
			if v.Constant {
				g.line("const " + goIdent(v.Names[0]) + " " + typ + " = " + g.expr(v.Value))
			} else {
				names := make([]string, 0, len(v.Names))
				for _, n := range v.Names {
					names = append(names, goIdent(n))
				}
				g.line("var " + strings.Join(names, ", ") + " " + typ)
			}
		}
	}

	if len(prog.Decls) > 0 {
		g.line("")
	}

	g.line("func main() {")
	g.indent++
	for _, s := range prog.Body {
		g.stmt(s)
	}
	g.indent--
	g.line("}")

	formatted, err := format.Source([]byte(g.b.String()))
	if err != nil {
		return g.b.String(), fmt.Errorf("could not format generated Go code: %w", err)
	}
	return string(formatted), nil
}

func (g *CodeGenerator) scanRuntimeNeeds(s Stmt) {
	switch v := s.(type) {
	case InputStmt, OutputStmt:
		g.needsFmt = true
	case ForStmt:
		for _, x := range v.Body {
			g.scanRuntimeNeeds(x)
		}
	case WhileStmt:
		for _, x := range v.Body {
			g.scanRuntimeNeeds(x)
		}
	case IfStmt:
		for _, x := range v.Then {
			g.scanRuntimeNeeds(x)
		}
		for _, x := range v.Else {
			g.scanRuntimeNeeds(x)
		}
	case RepeatStmt:
		for _, x := range v.Body {
			g.scanRuntimeNeeds(x)
		}
	case SwitchStmt:
		for _, cl := range v.Cases {
			for _, x := range cl.Body {
				g.scanRuntimeNeeds(x)
			}
		}
		for _, x := range v.Default {
			g.scanRuntimeNeeds(x)
		}
	}
}

func (g *CodeGenerator) stmt(s Stmt) {
	switch v := s.(type) {
	case AssignStmt:
		g.line(func() string {
			if v.Target != nil {
				return g.expr(v.Target)
			}
			return g.identifier(v.Name)
		}() + " = " + g.expr(v.Value))
	case InputStmt:
		if len(v.Targets) > 0 {
			for _, t := range v.Targets {
				target := g.expr(t)
				rawName := g.exprToRawName(t)
				if strings.EqualFold(g.inputType(rawName), "char") {
					g.line("fmt.Scanf(\"%c\", &" + target + ")")
				} else {
					g.line("fmt.Scan(&" + target + ")")
				}
			}
		} else {
			for _, n := range v.Names {
				target := g.inputTarget(n)
				if strings.EqualFold(g.inputType(n), "char") {
					g.line("fmt.Scanf(\"%c\", &" + target + ")")
				} else {
					g.line("fmt.Scan(&" + target + ")")
				}
			}
		}

	case OutputStmt:
		args := []string{}
		for _, e := range v.Values {
			args = append(args, g.expr(e))
		}
		g.line("fmt.Println(" + strings.Join(args, ", ") + ")")

	case ForStmt:
		cmp, step := "<=", "++"
		if v.Down {
			cmp, step = ">=", "--"
		}

		counter := g.identifier(v.Counter)

		g.line(
			"for " + counter +
				" = " + g.expr(v.Start) +
				"; " + counter + " " + cmp + " " +
				g.expr(v.End) +
				"; " + counter + step + " {",
		)

		g.indent++
		for _, x := range v.Body {
			g.stmt(x)
		}
		g.indent--
		g.line("}")

	case WhileStmt:
		g.line("for " + g.expr(v.Condition) + " {")
		g.indent++
		for _, x := range v.Body {
			g.stmt(x)
		}
		g.indent--
		g.line("}")
	case IfStmt:
		g.genIf(v)
	case RepeatStmt:
		g.line("for {")
		g.indent++
		for _, x := range v.Body {
			g.stmt(x)
		}
		g.line("if " + g.expr(v.Condition) + " {")
		g.indent++
		g.line("break")
		g.indent--
		g.line("}")
		g.indent--
		g.line("}")
	case SwitchStmt:
		g.line("switch " + g.expr(v.Expr) + " {")
		for _, cl := range v.Cases {
			var vals []string
			for _, val := range cl.Values {
				vals = append(vals, g.expr(val))
			}
			g.line("case " + strings.Join(vals, ", ") + ":")
			g.indent++
			for _, x := range cl.Body {
				g.stmt(x)
			}
			g.indent--
		}
		if len(v.Default) > 0 {
			g.line("default:")
			g.indent++
			for _, x := range v.Default {
				g.stmt(x)
			}
			g.indent--
		}
		g.line("}")
	}
}

func (g *CodeGenerator) expr(e Expr) string {
	switch v := e.(type) {
	case LiteralExpr:
		switch v.Kind {
		case TokenIdent:
			if v.Value == "benar" || v.Value == "true" {
				return "true"
			}
			if v.Value == "salah" || v.Value == "false" {
				return "false"
			}
			return v.Value
		default:
			return v.Value
		}
	case IdentExpr:
		return g.identifier(v.Name)
	case FieldExpr:
		return g.expr(v.Base) + "." + goIdent(v.Field)
	case UnaryExpr:
		op := v.Op
		if op == "NOT" {
			op = "!"
		}
		return "(" + op + g.expr(v.Right) + ")"
	case BinaryExpr:
		op := v.Op
		switch op {
		case "DIV":
			op = "/"
		case "MOD":
			op = "%"
		case "AND":
			op = "&&"
		case "OR":
			op = "||"
		case "XOR":
			op = "!="
		case "=":
			op = "=="
		case "/=", "<>", "!=":
			op = "!="
		}
		left, right := g.expr(v.Left), g.expr(v.Right)
		if v.Op == "/" {
			left = "float64(" + left + ")"
			right = "float64(" + right + ")"
		}
		return "(" + left + " " + op + " " + right + ")"
	case CastExpr:
		return goType(v.TargetType) + "(" + g.expr(v.Expr) + ")"
	}
	return "/* invalid expression */"
}

func (g *CodeGenerator) genIf(v IfStmt) {
	g.line("if " + g.expr(v.Condition) + " {")
	g.indent++
	for _, x := range v.Then {
		g.stmt(x)
	}
	g.indent--

	currElse := v.Else
	for len(currElse) == 1 {
		if nextIf, ok := currElse[0].(IfStmt); ok {
			g.line("} else if " + g.expr(nextIf.Condition) + " {")
			g.indent++
			for _, x := range nextIf.Then {
				g.stmt(x)
			}
			g.indent--
			currElse = nextIf.Else
			continue
		}
		break
	}

	if len(currElse) > 0 {
		g.line("} else {")
		g.indent++
		for _, x := range currElse {
			g.stmt(x)
		}
		g.indent--
	}
	g.line("}")
}

// QuoteForDiagnostic is used by tests and CLI diagnostics.
func QuoteForDiagnostic(s string) string { return strconv.Quote(s) }
